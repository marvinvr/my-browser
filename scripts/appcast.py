#!/usr/bin/env python3
"""Sparkle appcast for myBrowser (used by scripts/release.sh).

releases.json is the record (one entry per release, newest build first). appcast.xml is rendered
from it and is what SUFeedURL reads. Every command is idempotent.

  appcast.py query  DB latest-version | latest-build | latest-commit | has-version V | count
  appcast.py upsert DB --version V --build B --commit SHA --url URL --length N --signature SIG
                        --min-system 26.0 --notes-file FILE [--page URL]
  appcast.py render DB OUT --feed-url URL [--title TITLE]
  appcast.py notes  SUBJECTS_FILE OUT_MD
"""
import argparse
import email.utils
import html
import json
import os
import re
import sys
import tempfile
from datetime import datetime, timezone

MAX_APPCAST_ITEMS = 20


def load(db):
    if not os.path.exists(db) or os.path.getsize(db) == 0:
        return {"releases": []}
    with open(db) as f:
        data = json.load(f)
    data.setdefault("releases", [])
    return data


def write_atomic(path, text):
    folder = os.path.dirname(os.path.abspath(path)) or "."
    os.makedirs(folder, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=folder, prefix=".tmp-")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


def newest(data):
    releases = data["releases"]
    return max(releases, key=lambda r: int(r["build"])) if releases else None


def cmd_query(args):
    data = load(args.db)
    latest = newest(data)
    what = args.what
    if what == "latest-version":
        print(latest["version"] if latest else "")
    elif what == "latest-build":
        print(latest["build"] if latest else "0")
    elif what == "latest-commit":
        print(latest.get("commit", "") if latest else "")
    elif what == "has-version":
        sys.exit(0 if any(r["version"] == args.arg for r in data["releases"]) else 1)
    elif what == "count":
        print(len(data["releases"]))
    else:
        sys.exit(f"unknown query {what}")


def cmd_upsert(args):
    data = load(args.db)
    with open(args.notes_file) as f:
        notes = [line[2:].strip() for line in f if line.startswith("- ")]
    entry = {
        "version": args.version,
        "build": str(args.build),
        "commit": args.commit,
        "date": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "url": args.url,
        "length": int(args.length),
        "edSignature": args.signature,
        "minimumSystemVersion": args.min_system,
        "notes": notes,
    }
    if args.page:
        entry["page"] = args.page
    old = next((r for r in data["releases"] if r["version"] == args.version), None)
    if old:
        entry["date"] = old.get("date", entry["date"])
    data["releases"] = [r for r in data["releases"] if r["version"] != args.version] + [entry]
    data["releases"].sort(key=lambda r: int(r["build"]), reverse=True)
    write_atomic(args.db, json.dumps(data, indent=2) + "\n")


def notes_html(notes):
    if not notes:
        return "<p>Maintenance release.</p>"
    return "<ul>" + "".join(f"<li>{html.escape(n)}</li>" for n in notes) + "</ul>"


def cmd_render(args):
    data = load(args.db)
    items = []
    for r in data["releases"][:MAX_APPCAST_ITEMS]:
        date = datetime.strptime(r["date"], "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
        page = ""
        if r.get("page"):
            page = f"\n      <sparkle:fullReleaseNotesLink>{html.escape(r['page'])}</sparkle:fullReleaseNotesLink>"
        items.append(f"""    <item>
      <title>Version {html.escape(r['version'])}</title>
      <pubDate>{email.utils.format_datetime(date)}</pubDate>
      <sparkle:version>{html.escape(r['build'])}</sparkle:version>
      <sparkle:shortVersionString>{html.escape(r['version'])}</sparkle:shortVersionString>
      <sparkle:minimumSystemVersion>{html.escape(r['minimumSystemVersion'])}</sparkle:minimumSystemVersion>{page}
      <description><![CDATA[{notes_html(r.get('notes', []))}]]></description>
      <enclosure url="{html.escape(r['url'], quote=True)}" length="{r['length']}" type="application/octet-stream" sparkle:edSignature="{html.escape(r['edSignature'])}"/>
    </item>""")
    body = "\n".join(items)
    if body:
        body = "\n" + body + "\n"
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/release.sh from releases.json. Don't edit by hand. -->
<rss version="2.0" xmlns:sparkle="http://www.andymatuschak.org/xml-namespaces/sparkle">
  <channel>
    <title>{html.escape(args.title)}</title>
    <link>{html.escape(args.feed_url)}</link>
    <description>Updates of myBrowser</description>
    <language>en</language>{body}  </channel>
</rss>
"""
    write_atomic(args.out, xml)


CONVENTIONAL = re.compile(r"^(\w+)(\([^)]*\))?!?:\s*")
SKIP_TYPES = {"docs", "test", "tests", "chore", "ci", "build", "style"}


def cmd_notes(args):
    lines = []
    with open(args.subjects) as f:
        for raw in f:
            subject = raw.strip()
            if not subject or subject.startswith("Merge "):
                continue
            match = CONVENTIONAL.match(subject)
            if match:
                if match.group(1).lower() in SKIP_TYPES:
                    continue
                subject = subject[match.end():]
            subject = re.sub(r"\s*\(#\d+\)$", "", subject)
            if not subject:
                continue
            subject = subject[0].upper() + subject[1:]
            if subject not in lines:
                lines.append(subject)
    lines = lines[:15] or ["Maintenance release."]
    write_atomic(args.out, "".join(f"- {line}\n" for line in lines))


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="cmd", required=True)

    query = sub.add_parser("query")
    query.add_argument("db")
    query.add_argument("what")
    query.add_argument("arg", nargs="?")

    upsert = sub.add_parser("upsert")
    upsert.add_argument("db")
    for name in ("version", "build", "commit", "url", "length", "signature", "min-system", "notes-file"):
        upsert.add_argument(f"--{name}", required=True)
    upsert.add_argument("--page")

    render = sub.add_parser("render")
    render.add_argument("db")
    render.add_argument("out")
    render.add_argument("--feed-url", required=True)
    render.add_argument("--title", default="myBrowser")

    notes = sub.add_parser("notes")
    notes.add_argument("subjects")
    notes.add_argument("out")

    args = parser.parse_args()
    if args.cmd == "upsert":
        if not re.fullmatch(r"\d+\.\d+\.\d+", args.version) or not str(args.build).isdigit():
            sys.exit("bad version / build")
    {
        "query": cmd_query,
        "upsert": cmd_upsert,
        "render": cmd_render,
        "notes": cmd_notes,
    }[args.cmd](args)


if __name__ == "__main__":
    main()
